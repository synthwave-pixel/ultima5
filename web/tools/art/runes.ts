/**
 * runes.ts
 *
 * The Standard look's English for the runes (public/graphics/standard-runes.png): what the runes read into where the
 * fonts cannot be had (the Standard lettering, Sixtyfour, as the game sets them otherwise). One glyph of 16 by 16 for
 * each rune letter in the runes' own order, A to Z, then the five runes that stand for two letters - TH, EE, NG, EA
 * and ST - each one cell, so a sign keeps its shape. The screen doubles them by EPX, as it does the Standard lettering.
 *
 * The letters are Sixtyfour's (Jens Kutilek, SIL Open Font License 1.1, public/fonts/OFL-sixtyfour.txt), taken from
 * the font at the size where each of its pixels is two by two: its seven rows from the second down, centred across.
 * A pair's two letters are squeezed side by side, each of its pixels one across and two down, as the lettering
 * squeezes them into one cell. Run:
 *
 *   npm run runes
 */

