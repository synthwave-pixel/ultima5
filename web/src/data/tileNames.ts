export const TILE_NAMES: string[] = new Array<string>(512).fill('');
for (const [i, n] of MAP) TILE_NAMES[i] = n;
for (const [i, n, frames] of ACTORS) {
  for (let f = 0; f < frames; f++) TILE_NAMES[0x100 + i + f] = frames > 1 ? `${n} ${f + 1}` : n;
}

/** Tiles the map draws as a square's ground (the rest stand on one, over it where their art lets it show). */
export function isTerrain(tile: number): boolean {
  return tile < 0x100;
}
